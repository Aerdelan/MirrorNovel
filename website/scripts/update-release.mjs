import { readFile, writeFile, rename } from 'node:fs/promises';
const path = new URL('../site.config.json', import.meta.url);
const config = JSON.parse(await readFile(path, 'utf8'));
const headers = { 'User-Agent': 'MirrorNovel-Website-Release-Updater' };
const response = await fetch(`${config.repository}/releases/latest`, { headers, signal: AbortSignal.timeout(20000) });
if (!response.ok) throw new Error(`Release page: HTTP ${response.status}`);
const tag = decodeURIComponent(new URL(response.url).pathname.split('/').at(-1));
const fragment = await fetch(`${config.repository}/releases/expanded_assets/${encodeURIComponent(tag)}`, { headers, signal: AbortSignal.timeout(20000) });
if (!fragment.ok) throw new Error(`Release assets: HTTP ${fragment.status}`);
const prefix = new URL(config.repository).pathname + '/releases/download/';
const links = Array.from((await fragment.text()).matchAll(/href="([^"]+\.exe)"/g), match => match[1].replaceAll('&amp;', '&')).filter(link => link.startsWith(prefix) && /MirrorNovel[. _-]Setup/i.test(decodeURIComponent(link)));
if (links.length !== 1) throw new Error(`Expected one Windows installer; found ${links.length}. Configuration unchanged.`);
const url = new URL(links[0], config.repository).href;
const head = await fetch(url, { method: 'HEAD', headers, signal: AbortSignal.timeout(20000) });
if (!head.ok || /text\/html/.test(head.headers.get('content-type') || '')) throw new Error('Installer is not a downloadable binary; configuration unchanged.');
const file = decodeURIComponent(new URL(url).pathname.split('/').at(-1));
const version = file.match(/Setup[. _-](\d+\.\d+\.\d+)/i)?.[1];
if (!version) throw new Error('Unrecognized installer version; configuration unchanged.');
const verified = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Shanghai', year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date());
config.release = { tag, version, file, url, verified };
await writeFile(new URL('../site.config.json.next', import.meta.url), JSON.stringify(config, null, 2) + '\n');
await rename(new URL('../site.config.json.next', import.meta.url), path);
console.log(`Verified ${tag} · ${file}. Run npm run build to publish the updated link.`);
