/**
 * 为指定 userId 写入系统预设（幂等：已存在同名则跳过）
 * 返回写入数量
 */
async function seedSystemPersonas(userId) {
  if (!userId) return 0
  const WritingPersona = require('../models/WritingPersona')
  let inserted = 0
  for (const p of BUILTIN_SYSTEM_PERSONAS) {
    const exists = await WritingPersona.findOne({ userId, name: p.name, isSystem: true })
    if (exists) continue
    await WritingPersona.create({
      ...p,
      userId,
      source: 'system',
      isSystem: true,
    })
    inserted++
  }
  return inserted
}

