/**
 * ╔══════════════════════════════════════════════════════════════════╗
 * ║          Novel Editing Rule Engine — 规则引擎蓝图设计             ║
 * ║          (Novel Editing Rule Engine Blueprint)                    ║
 * ╚══════════════════════════════════════════════════════════════════╝
 *
 * 本文件是未来版本的架构蓝图，当前版本（v3）尚未实现此架构。
 * 后续版本将基于此蓝图逐步实装，最终替代当前的"全 Prompt"方案。
 *
 * ─────────────────────────────────────────────────────────────────────
 *
 * ## 核心理念
 *
 *   不要做"词库"，做"规则引擎"。
 *   词库容易被耗尽，也容易形成新的模板。
 *   规则引擎关注的是**为什么这句话像AI、应该改成什么表达方式**，
 *   它不绑定具体词，而是绑定**编辑决策**。
 *
 *   模型换了，产品能力依然保留。
 *   真正的核心竞争力在规则引擎里，而不是某一个模型的 Prompt。
 *
 * ─────────────────────────────────────────────────────────────────────
 *
 * ## 四层架构
 *
 * ┌─────────────────────────────────────────────────────────┐
 * │  第一层：规则层（Rule Layer）                           │
 * │  ★★★★★★★★★                                       │
 * │                                                         │
 * │  200+ 条编辑规则，纯程序逻辑，不需要 AI                  │
 * │  类型：禁用模式检测、替换规则、结构重组规则               │
 * │  作用：在 LLM 之前预处理、在 LLM 之后后处理               │
 * │                                                         │
 * │  规则示例：                                              │
 * │  Rule001: 删除解释 — before: "在这个世界" → after: 删除  │
 * │  Rule002: 删除总结 — before: "这意味着" → after: 删除    │
 * │  Rule003: 心理改动作 — before: "他心中一惊" → 生成动作   │
 * │  Rule004: 世界观 — before: 作者介绍 → after: 人物经历    │
 * └─────────────────────────────────────────────────────────┘
 *                          ↓
 * ┌─────────────────────────────────────────────────────────┐
 * │  第二层：分析层（Analysis Layer）                        │
 * │  ★★★★★★★★★                                       │
 * │                                                         │
 * │  小说 AST（抽象语法树） + 统计分析                       │
 * │  纯程序，不调 LLM                                       │
 * │                                                         │
 * │  句子级 AST 节点：                                       │
 * │  {                                                      │
 * │    type: "action" | "emotion" | "dialogue" |             │
 * │          "environment" | "psychology" | "setting" |     │
 * │          "narration" | "battle",                         │
 * │    emotion: "nervous" | "angry" | "calm" | ...,         │
 * │    character: "角色名",                                  │
 * │    importance: 0.0-1.0,                                  │
 * │    sentenceLength: 字数,                                 │
 * │    paragraphIndex: 段落序号                              │
 * │  }                                                      │
 * │                                                         │
 * │  统计输出：                                              │
 * │  - 对白占比 / 环境占比 / 动作占比 / 心理占比 / 介绍占比   │
 * │  - 句长分布直方图（Burstiness 指标）                     │
 * │  - 段落长度分布                                          │
 * │  - AI 模式检测（环境→人物→动作→能力 的标准开头）         │
 * │  - 重复表达检测                                          │
 * └─────────────────────────────────────────────────────────┘
 *                          ↓
 * ┌─────────────────────────────────────────────────────────┐
 * │  第三层：LLM 层（Generation Layer）                      │
 * │  ★★★★★                                              │
 * │                                                         │
 * │  只负责生成，一句一句，不是全文                           │
 * │  Token 消耗极低（每句几十 token）                       │
 * │                                                         │
 * │  工作方式：                                              │
 * │  1. 分析层识别出需要改写的句子                            │
 * │  2. 根据句子类型 + 上下文，构建极小 Prompt               │
 * │  3. LLM 只生成一句替代文本                               │
 * │                                                         │
 * │  示例 Prompt（仅几十 token）：                           │
 * │  角色：拾荒者，文化低                                    │
 * │  不要心理，改动作                                        │
 * │  一句。                                                  │
 * │                                                         │
 * │  输出：                                                  │
 * │  "他脚步顿了一下。" 或                                    │
 * │  "他下意识攥紧撬棍。" 或                                    │
 * │  "他没说话，只是把袖口往上一卷。"                           │
 * │                                                         │
 * │  不是固定替换，每次不同。                                 │
 * └─────────────────────────────────────────────────────────┘
 *                          ↓
 * ┌─────────────────────────────────────────────────────────┐
 * │  第四层：统计学习层（Statistical Learning Layer）        │
 * │  ★★★★★★★★★★                                    │
 * │                                                         │
 * │  越用越强，自动进化                                      │
 * │                                                         │
 * │  数据来源：                                              │
 * │  - 用户上传的 100 万章小说                               │
 * │  - 起点 TOP100 统计                                      │
 * │  - 番茄热门小说统计                                      │
 * │  - 用户编辑行为反馈                                      │
 * │                                                         │
 * │  自动学习：                                              │
 * │  - 统计真人小说中"握紧拳头"出现率（如 0.12%）             │
 * │  - 统计 AI 输出中"握紧拳头"出现率（如 7.4%）              │
 * │  - 差异大的表达自动加入"高风险表达"规则库                 │
 * │  - 统计真人第一章对白/环境/动作/心理/介绍占比              │
 * │  - 对比 AI 输出占比，自动生成分布调整规则                 │
 * │                                                         │
 * │  最终形态：                                              │
 * │  312 条编辑规则                                          │
 * │  185 种 AI 模式                                          │
 * │  98 种节奏模式                                           │
 * │  42 种人物语言                                           │
 * │  76 种世界观介绍方式                                     │
 * │  54 种战斗节奏                                           │
 * └─────────────────────────────────────────────────────────┘
 *
 * ─────────────────────────────────────────────────────────────────────
 *
 * ## 规则 DSL（领域规则语言）设计
 *
 * 规则不绑定具体词，而是绑定编辑决策。
 *
 * rule:
 *   id: Rule003
 *   name: 心理改动作
 *   match:
 *     type: emotion          # AST 节点类型
 *     emotion: nervous       # 情绪标签
 *     pattern: "心中一惊"    # 可选：正则匹配
 *   action:
 *     type: regenerate       # 重新生成
 *     prompt:
 *       character_role: ${node.character}
 *       education: low
 *       instruction: "不要心理，改动作"
 *       max_length: 10
 *     fallback:              # LLM 不可用时的降级策略
 *       type: delete         # 直接删除
 *
 * ─────────────────────────────────────────────────────────────────────
 *
 * ## 模式检测器（Pattern Detector）设计
 *
 * 不检测词，检测"模式"（Pattern）。
 *
 * AI 喜欢的模式：
 *   环境 → 人物 → 解释 → 剧情
 *
 * 程序发现后直接重排为：
 *   人物 → 动作 → 对白 → 环境
 *
 * 这里根本不用词库。
 *
 * pattern:
 *   id: StandardOpening
 *   name: 标准开头模式
 *   detect:
 *     sequence: [environment, character, narration, ability]
 *     window: 4              # 检测前4个段落
 *   fix:
 *     type: reorder
 *     target: [character, action, dialogue, environment]
 *
 * ─────────────────────────────────────────────────────────────────────
 *
 * ## 作者语料库（Author Corpus）设计
 *
 * 收集 1000 本番茄小说，程序分析真人写作的语言分布：
 *
 *   第一章平均分布：
 *   对白 32%
 *   环境 12%
 *   动作 28%
 *   心理  9%
 *   介绍 19%
 *
 * 然后对比 AI 输出：
 *   对白 15%  ← 偏低，自动补充
 *
 * 不是替换词，而是调整整个语言分布。
 *
 * corpus:
 *   source: fanqie_top100
 *   chapter: 1
 *   distribution:
 *     dialogue: 0.32
 *     environment: 0.12
 *     action: 0.28
 *     psychology: 0.09
 *     exposition: 0.19
 *   sentence_length:
 *     mean: 18
 *     stddev: 22          # 真人句长标准差很大
 *     ultra_short_rate: 0.08   # 每100句8句是极短句
 *
 * ─────────────────────────────────────────────────────────────────────
 *
 * ## 实装路线图
 *
 * Phase 1 (v4): 规则层基础 + 分析层基础
 *   - 实现禁用词/句式检测器（正则 + AST）
 *   - 实现句子级 AST 解析器
 *   - 实现句长分布统计器（Burstiness 指标）
 *   - 在 LLM 前后增加规则预处理/后处理
 *   - 规则存储在 editorialRules.js 的 rules 数组中
 *
 * Phase 2 (v5): 模式检测 + 局部 LLM 改写
 *   - 实现标准开头模式检测器
 *   - 实现重复结构检测器
 *   - 对需要改写的句子构建极小 Prompt 调 LLM
 *   - Token 消耗降低 80%+
 *
 * Phase 3 (v6): 统计学习层
 *   - 收集用户编辑行为数据
 *   - 统计真人小说语言分布
 *   - 自动生成高风险表达规则
 *   - 规则库自动扩充
 *
 * Phase 4 (v7): 完整规则引擎
 *   - 规则 DSL 完整实现
 *   - 作者语料库建立
 *   - 多模型适配（GPT/Claude/Gemini/Qwen）
 *   - 规则引擎完全替代 Prompt 驱动
 *
 * ─────────────────────────────────────────────────────────────────────
 *
 * ## 当前版本（v3）与蓝图的关系
 *
 * v3 是"全 Prompt 驱动"的过渡版本：
 *   - 8 阶段 Pipeline（persona 本地生成 + 7 次 LLM 调用）
 *   - 每阶段发送全文，Token 消耗较大
 *   - Prompt 中内嵌了规则（将在 v4 拆出为独立规则层）
 *   - editorialRules.js 是规则 DSL 的雏形
 *
 * v4+ 将逐步把 Prompt 中的规则迁移到独立的规则层，
 * 最终实现"LLM 只负责一句一句的局部生成"。
 */

